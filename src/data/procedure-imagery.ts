/**
 * procedure-imagery — single source of truth for the before/after
 * gallery assets used by the patient-facing /procedures/[slug] page.
 *
 * Each entry maps a procedure slug (matching `data/procedures.ts`) to
 * the public-folder paths of one before/after pair. When a procedure
 * is NOT in this map, the procedure page silently skips the comparison
 * slider — no broken-image artefact is shown.
 *
 * Adding a new procedure pair:
 *   1. Drop the pair into `public/images/gallery/` named
 *      `<slug>-<patient-name>-before.webp` + `-after.webp`
 *   2. Add an entry below pointing at those filenames
 *
 * The optional `subjectName` is rendered as a small attribution caption
 * under the slider so patients understand they're seeing a real
 * (consented) result, not a stock photo. Leave undefined to omit.
 */

export interface ProcedureImageryEntry {
    /** Public-folder path (starts with `/`) */
    beforeSrc: string;
    /** Public-folder path (starts with `/`) */
    afterSrc: string;
    /** alt text — patient sees nothing literal so describe the visible state */
    beforeAlt: string;
    afterAlt: string;
    /** Optional patient first name + region for caption (with consent on file) */
    subjectCaption?: string;
}

